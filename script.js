const header = document.querySelector('.site-header');
const menuToggle = document.querySelector('.menu-toggle');
const menu = document.querySelector('.main-menu');
const languageButtons = document.querySelectorAll('[data-language]');
const formStatus = document.querySelector('.form-status');
const form = document.querySelector('.contact-form');

function setLanguage(language, persist = true) {
  const selectedLanguage = copy[language] ? language : 'no';
  const translations = copy[selectedLanguage];
  document.documentElement.lang = selectedLanguage;
  document.title = selectedLanguage === 'no' ? 'Rise Digital – Digitale løsninger for bedrifter' : 'Rise Digital – Digital solutions for businesses';
  document.querySelector('meta[name="description"]').content = selectedLanguage === 'no'
    ? 'Rise Digital hjelper bedrifter med nettsider, annonsering, digitale produkter og en tydeligere vei fra interesse til salg.'
    : 'Rise Digital helps businesses with websites, advertising, digital products and a clearer path from interest to sale.';
  document.querySelector('meta[property="og:title"]').content = document.title;
  document.querySelector('meta[property="og:description"]').content = selectedLanguage === 'no'
    ? 'Nettsider, annonsering og digitale salgsløsninger tilpasset bedriften din.'
    : 'Websites, advertising and digital sales solutions shaped around your business.';
  document.querySelector('meta[property="og:locale"]').content = selectedLanguage === 'no' ? 'nb_NO' : 'en_GB';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.innerHTML = translations[element.dataset.i18n];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = translations[element.dataset.i18nPlaceholder];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', translations[element.dataset.i18nAria]);
  });
  document.querySelectorAll('[data-i18n-value]').forEach((element) => {
    element.value = translations[element.dataset.i18nValue];
  });
  languageButtons.forEach((button) => {
    const active = button.dataset.language === selectedLanguage;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  if (formStatus) {
    const state = formStatus.dataset.state;
    if (state === 'success') formStatus.textContent = translations.sent;
    if (state === 'error') formStatus.textContent = translations.sendError;
    if (state === 'loading') formStatus.textContent = translations.sending;
  }
  if (persist) {
    try { localStorage.setItem('rise-digital-language', selectedLanguage); } catch {}
  }
}

function closeMenu() {
  header.classList.remove('menu-open');
  menuToggle.setAttribute('aria-expanded', 'false');
  menuToggle.setAttribute('aria-label', copy[document.documentElement.lang].menuOpen);
}

menuToggle.addEventListener('click', () => {
  const open = menuToggle.getAttribute('aria-expanded') !== 'true';
  header.classList.toggle('menu-open', open);
  menuToggle.setAttribute('aria-expanded', String(open));
  menuToggle.setAttribute('aria-label', open ? copy[document.documentElement.lang].menuClose : copy[document.documentElement.lang].menuOpen);
});

menu.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') closeMenu();
});
languageButtons.forEach((button) => button.addEventListener('click', () => {
  setLanguage(button.dataset.language);
  closeMenu();
}));

form.addEventListener('submit', async (event) => {
  event.preventDefault();
  const submitButton = form.querySelector('.form-submit');
  submitButton.disabled = true;
  form.setAttribute('aria-busy', 'true');
  formStatus.dataset.state = 'loading';
  formStatus.textContent = copy[document.documentElement.lang].sending;
  try {
    const response = await fetch(form.action, {
      method: 'POST',
      body: new FormData(form),
      headers: { Accept: 'application/json' }
    });
    if (!response.ok) throw new Error('Form submission failed');
    formStatus.dataset.state = 'success';
    formStatus.textContent = copy[document.documentElement.lang].sent;
    form.reset();
  } catch {
    formStatus.dataset.state = 'error';
    formStatus.textContent = copy[document.documentElement.lang].sendError;
  } finally {
    submitButton.disabled = false;
    form.removeAttribute('aria-busy');
  }
});

document.getElementById('year').textContent = new Date().getFullYear();
let initialLanguage = 'no';
try { initialLanguage = localStorage.getItem('rise-digital-language') || 'no'; } catch {}
setLanguage(initialLanguage, false);
